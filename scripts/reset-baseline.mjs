#!/usr/bin/env node
/* =============================================================================
   Reset the "Downloads Since Launch" baseline.

   The site shows (live GitHub download_count − baseline), so moving the baseline
   forward to the current counters sets the public figure back to 0 and starts
   tracking again from that moment.

   Numbers are read from the GitHub API at run time, never typed by hand, so the
   baseline is always an exact snapshot of what GitHub is reporting.

   Usage:
     node scripts/reset-baseline.mjs            # write the new snapshot
     node scripts/reset-baseline.mjs --dry-run  # show what it would write
     GITHUB_TOKEN=… node scripts/reset-baseline.mjs   # optional, avoids rate limits

   This does NOT and CANNOT change GitHub's own all-time download counters — those
   live on GitHub's servers and are the real record. It only moves the point from
   which this website counts.
   ============================================================================= */

import { writeFile, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';

const OWNER = 'blazemc125';
const REPO = 'AzyronClient';
const TAG = 'azyronclient-v1.0.0';
const OUT = new URL('../docs/data/counter-baseline.json', import.meta.url);

const dryRun = process.argv.includes('--dry-run');

const kindOf = (name = '') => {
  const lower = String(name).toLowerCase();
  if (lower.endsWith('.jar')) return 'jar';
  if (lower.endsWith('.mrpack')) return 'mrpack';
  if (lower.endsWith('.zip')) return 'zip';
  return 'file';
};

const url = `https://api.github.com/repos/${OWNER}/${REPO}/releases/tags/${encodeURIComponent(TAG)}`;

const headers = { Accept: 'application/vnd.github+json' };
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

const response = await fetch(url, { headers });

if (!response.ok) {
  console.error(`✗ GitHub API responded ${response.status} — baseline NOT changed.`);
  if (response.status === 403) console.error('  (rate limited; retry shortly or set GITHUB_TOKEN)');
  process.exit(1);
}

const release = await response.json();
const assets = release.assets || [];

if (!assets.length) {
  console.error('✗ The release has no assets — refusing to write an empty baseline.');
  process.exit(1);
}

// Refuse to move the baseline *backwards*: that would resurrect downloads the
// site has already counted and reported, and the number would jump up for no
// real reason.
if (existsSync(OUT) && !process.argv.includes('--allow-backwards')) {
  const previous = JSON.parse(await readFile(OUT, 'utf8'));
  const regressions = [];
  for (const asset of assets) {
    const before = Number(previous.baseline?.[String(asset.id)]);
    if (Number.isFinite(before) && asset.download_count < before) {
      regressions.push(`${asset.name}: baseline ${before} → live ${asset.download_count}`);
    }
  }
  if (regressions.length) {
    console.error('✗ GitHub reports FEWER downloads than the stored baseline:');
    regressions.forEach((line) => console.error(`   ${line}`));
    console.error('  Writing this would make the site count downloads that already happened.');
    console.error('  Pass --allow-backwards only if you are certain (e.g. an asset was re-uploaded).');
    process.exit(1);
  }
}

const baseline = {};
const baselineByName = {};
const baselineByKind = {};
let baselineTotal = 0;

for (const asset of assets) {
  const count = Number(asset.download_count) || 0;
  baseline[String(asset.id)] = count;
  baselineByName[asset.name] = count;
  const kind = kindOf(asset.name);
  baselineByKind[kind] = (baselineByKind[kind] || 0) + count;
  baselineTotal += count;
}

const now = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');

const payload = {
  schemaVersion: 1,
  description:
    "AZYRON CLIENT download baseline. The website shows 'Downloads Since Launch' as (live GitHub count - baseline), so the counter starts at exactly 0 and every increment is a real download recorded by GitHub after this point. Only downloads made after this baseline count. Generated by scripts/reset-baseline.mjs — never edit these numbers by hand.",
  launchedAt: now,
  repo: `${OWNER}/${REPO}`,
  tag: release.tag_name || TAG,
  baselineTotal,
  baseline,
  baselineByName,
  baselineByKind,
};

const json = `${JSON.stringify(payload, null, 2)}\n`;

console.log(`GitHub release ${payload.tag}`);
for (const asset of assets) {
  console.log(`  ${asset.name.padEnd(34)} all-time ${String(asset.download_count).padStart(5)}  → baseline`);
}
console.log(`  ${'TOTAL'.padEnd(34)} all-time ${String(baselineTotal).padStart(5)}  → since launch will read 0`);
console.log(`\nlaunchedAt: ${now}`);

if (dryRun) {
  console.log('\n--dry-run: nothing written.');
  process.exit(0);
}

await writeFile(OUT, json);
console.log(`\n✓ wrote docs/data/counter-baseline.json — the site now counts from 0.`);
